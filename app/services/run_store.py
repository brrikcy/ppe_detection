"""Filesystem persistence for runs.

Layout:
    <data_dir>/<run_id>/
        meta.json        RunMeta (status, options, progress) - never the API key
        input.<ext>      uploaded video
        annotated.mp4    output video
        annotated.json   full per-frame report from ppe.video
        preview.jpg      latest analysed frame, annotated (updated while running)
        snapshots/       crop of each checked worker, per check
        frames/          full annotated frames that contain a violation, and each without boxes (<n>_clean.jpg)
        people/          best (largest) crop of each tracked person, <track_id>.jpg
"""

from __future__ import annotations

import json
import shutil
import threading
import time
import uuid
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

from ..schemas.runs import RunMeta, RunStatus


class RunNotFound(KeyError):
    pass


def replace_with_retry(src: Path, dst: Path, attempts: int = 10) -> None:
    """os.replace, retried: on Windows it fails while another handle has dst open."""
    for i in range(attempts):
        try:
            src.replace(dst)
            return
        except PermissionError:
            if i == attempts - 1:
                raise
            time.sleep(0.05)


@dataclass(frozen=True)
class RunPaths:
    root: Path

    @property
    def meta(self) -> Path:
        return self.root / "meta.json"

    @property
    def output(self) -> Path:
        return self.root / "annotated.mp4"

    @property
    def report(self) -> Path:
        return self.root / "annotated.json"

    @property
    def preview(self) -> Path:
        return self.root / "preview.jpg"

    @property
    def snapshots(self) -> Path:
        return self.root / "snapshots"

    @property
    def frames(self) -> Path:
        return self.root / "frames"

    @property
    def people(self) -> Path:
        return self.root / "people"

    def input(self) -> Path | None:
        return next(iter(sorted(self.root.glob("input.*"))), None)


class RunStore:
    def __init__(self, data_dir: Path):
        self.data_dir = data_dir
        self.data_dir.mkdir(parents=True, exist_ok=True)
        self._lock = threading.Lock()

    @staticmethod
    def new_id() -> str:
        stamp = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
        return f"{stamp}-{uuid.uuid4().hex[:6]}"

    def paths(self, run_id: str) -> RunPaths:
        # Run ids are generated by us; reject anything that could escape data_dir.
        if not run_id or "/" in run_id or "\\" in run_id or run_id.startswith("."):
            raise RunNotFound(run_id)
        return RunPaths(self.data_dir / run_id)

    def create_dir(self, run_id: str) -> RunPaths:
        p = self.paths(run_id)
        p.root.mkdir(parents=True)
        p.snapshots.mkdir()
        p.frames.mkdir()
        p.people.mkdir()
        return p

    def save(self, meta: RunMeta) -> None:
        p = self.paths(meta.id)
        tmp = p.meta.with_suffix(".tmp")
        with self._lock:
            tmp.write_text(meta.model_dump_json(indent=2))
            replace_with_retry(tmp, p.meta)

    def get(self, run_id: str) -> RunMeta:
        p = self.paths(run_id)
        if not p.meta.exists():
            raise RunNotFound(run_id)
        with self._lock:
            return RunMeta.model_validate_json(p.meta.read_text())

    def update(self, run_id: str, **changes) -> RunMeta:
        meta = self.get(run_id).model_copy(update=changes)
        self.save(meta)
        return meta

    def list(self) -> list[RunMeta]:
        metas = []
        for d in self.data_dir.iterdir():
            if (d / "meta.json").exists():
                try:
                    metas.append(self.get(d.name))
                except Exception:
                    continue  # skip corrupt run folders rather than break the list
        return sorted(metas, key=lambda m: m.created_at, reverse=True)

    def delete(self, run_id: str) -> None:
        p = self.paths(run_id)
        if not p.root.exists():
            raise RunNotFound(run_id)
        shutil.rmtree(p.root)

    def read_report(self, run_id: str) -> dict | None:
        p = self.paths(run_id)
        return json.loads(p.report.read_text()) if p.report.exists() else None

    def mark_interrupted(self) -> None:
        """Runs left queued/running by a previous server process can't resume."""
        for meta in self.list():
            if meta.status in (RunStatus.queued, RunStatus.running):
                self.save(meta.model_copy(update={
                    "status": RunStatus.failed,
                    "error": "Interrupted: the server stopped before this run finished.",
                }))
